// 生成演示页：node demo/build.js → demo/index.html
// 内联 three.js r108、2D 引擎（回退用）、3D 墓园引擎和首页头图
const fs = require('fs')
const path = require('path')
const root = path.join(__dirname, '..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const strip = (src) => src.replace(/^const \{[^}]+\} = require\('[^']+'\)\n/m, '').replace(/module\.exports = [^\n]+\n?/g, '')
const color = strip(read('scene/color.js'))
const engine = strip(read('scene/engine.js'))
const m3d = strip(read('scene3d/memorial3d.js')).replace(/^Memorial3D\.(PHASES|SEASONS) = .*$/mg, '')
const three = read('demo/three.r108.min.js')
const hero = 'data:image/jpeg;base64,' + fs.readFileSync(path.join(root, 'assets/hero.jpg')).toString('base64')
let html = read('demo/template.html')
html = html.replace('/*THREE*/', () => three)
html = html.replace('/*ENGINE*/', () => color + '\n' + engine + '\n' + m3d)
html = html.replace('/*HERO*/', () => hero)
fs.writeFileSync(path.join(__dirname, 'index.html'), html)
console.log('demo/index.html written', Math.round(html.length / 1024) + 'KB')
